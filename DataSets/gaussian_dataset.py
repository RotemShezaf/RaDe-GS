class GaussianPatchSubsetDataset(GaussianPatchDataset):
    """
    A ``GaussianPatchDataset`` that keeps only a random subset of examples.

    Use this to cap the number of training examples without regenerating
    data files, e.g. when the full combined dataset has millions of rows.

    Accepts either ``max_examples`` (absolute cap) **or**
    ``subset_fraction`` (relative cap in (0, 1]).  If both are given,
    ``max_examples`` wins.  Pass neither to get the full dataset (i.e.
    this behaves identically to ``GaussianPatchDataset``).
    """

    def __init__(
        self,
        *args,
        max_examples=None,
        subset_fraction=None,
        subset_seed=42,
        **kwargs,
    ):
        """
        Args:
            max_examples:    Keep at most this many examples.
            subset_fraction: Keep this fraction of examples (0 < f <= 1).
                             Ignored when ``max_examples`` is set.
            subset_seed:     RNG seed for the random subsample so that
                             the same subset is drawn every run.
            *args, **kwargs: Forwarded to ``GaussianPatchDataset.__init__``.
        """
        # Build the full dataset first
        super().__init__(*args, **kwargs)

        full_len = len(self.examples)

        # Resolve target size
        if max_examples is not None:
            target = min(max_examples, full_len)
        elif subset_fraction is not None:
            if not 0 < subset_fraction <= 1:
                raise ValueError(
                    f"subset_fraction must be in (0, 1], got {subset_fraction}"
                )
            target = max(1, int(full_len * subset_fraction))
        else:
            target = full_len  # no subsetting

        if target < full_len:
            gen = torch.Generator().manual_seed(subset_seed)
            indices = torch.randperm(full_len, generator=gen)[:target]
            indices, _ = indices.sort()  # keep storage order for cache locality

            if self.lazy_loading:
                # memmap → materialise the subset into a Tensor
                self.examples = torch.from_numpy(
                    np.array(self.examples[indices.numpy()])
                ).float()
                self.lazy_loading = False  # now in-memory
            else:
                self.examples = self.examples[indices]

            self.ring_info["num_examples"] = len(self.examples)
            print(
                f"Subset: kept {target:,} / {full_len:,} examples "
                f"({target / full_len:.1%}, seed={subset_seed})"
            )


class CombinedGaussianPatchDataset(Dataset):
    """
    Dataset that combines multiple GaussianPatchDataset sources.
    
    This allows training on data from multiple surfaces/textures combined.
    Supports two initialization modes:
    1. Multi-source config: A single config file with 'data_sources' list
       - Shared settings (attributes, rings, etc.) are taken from master config
       - Per-source settings (output_dir, weight) are merged in-memory
       - NO separate config.yaml files needed per source
    2. Config list: A list of individual config file paths (backward compatible)
       - Validates that shared settings are identical across all configs
    
    Supports weighted sampling from different sources.
    """
    
    def __init__(
        self,
        config: Union[str, Path, List[Union[str, Path]]],
        attributes: List[str] = None,
        ring: int = 2,
        use_r1_min: bool = False,
        transform: Optional[callable] = None,
        weights: Optional[List[float]] = None,
        lazy_loading: bool = False,
    ):
        """
        Initialize the combined dataset.
        
        Args:
            config: Either:
                - Path to a multi-source config YAML file (with 'data_sources' list)
                - List of paths to individual config YAML files
            attributes: List of attributes to include (must be common to all sources)
            ring: Ring number to load
            use_r1_min: If True, data includes r1_min_val
            transform: Optional transform to apply to features
            weights: Optional sampling weights (used with WeightedRandomSampler, only for config list mode)
            lazy_loading: If True, use memory-mapped loading in each sub-dataset.
        """
        self.datasets = []
        self.dataset_names = []
        self.dataset_weights = []
        self.cumulative_lengths = [0]
        self.transform = transform
        
        # Determine if config is a multi-source config or list of configs
        if isinstance(config, (str, Path)):
            config_path = Path(config)
            loaded_config = load_config(config_path)
            
            if is_multi_source_config(loaded_config):
                # Multi-source config mode - use in-memory config merging
                self._master_config = loaded_config
                sources = get_data_sources(loaded_config)
                
                for source in sources:
                    source_output_dir = source['output_dir']
                    if source_output_dir is None:
                        raise ValueError(f"Source '{source['name']}' missing output_dir")
                    
                    # Merge shared settings from master config with per-source settings
                    # This creates a complete config dict IN-MEMORY (no disk config needed)
                    merged_config = merge_source_config(loaded_config, source)
                    
                    dataset = GaussianPatchDataset(
                        config=merged_config,  # Pass dict directly
                        attributes=attributes,
                        ring=ring,
                        use_r1_min=use_r1_min,
                        transform=transform,
                        lazy_loading=lazy_loading,
                    )
                    self.datasets.append(dataset)
                    self.dataset_names.append(source['name'])
                    self.dataset_weights.append(source.get('weight', 1.0))
                    self.cumulative_lengths.append(self.cumulative_lengths[-1] + len(dataset))
            else:
                # Single config, wrap as single-source
                dataset = GaussianPatchDataset(
                    config=config_path,
                    attributes=attributes,
                    ring=ring,
                    use_r1_min=use_r1_min,
                    transform=transform,
                    lazy_loading=lazy_loading,
                )
                self.datasets.append(dataset)
                self.dataset_names.append(config_path.stem)
                self.dataset_weights.append(1.0)
                self.cumulative_lengths.append(len(dataset))
                self._master_config = loaded_config
        else:
            # List of config paths mode (backward compatible)
            config_paths = config
            self._master_config = None
            loaded_configs = []
            
            for i, cfg_path in enumerate(config_paths):
                cfg_path = Path(cfg_path)
                loaded_cfg = load_config(cfg_path)
                loaded_configs.append(loaded_cfg)
                
                dataset = GaussianPatchDataset(
                    config=cfg_path,
                    attributes=attributes,
                    ring=ring,
                    use_r1_min=use_r1_min,
                    transform=transform,
                    lazy_loading=lazy_loading,
                )
                self.datasets.append(dataset)
                self.dataset_names.append(cfg_path.stem)
                weight = weights[i] if weights and i < len(weights) else 1.0
                self.dataset_weights.append(weight)
                self.cumulative_lengths.append(self.cumulative_lengths[-1] + len(dataset))
            
            # Validate that shared settings are identical across all configs
            if len(loaded_configs) > 1:
                validate_shared_settings(loaded_configs)
        
        self.total_length = self.cumulative_lengths[-1]
        
        # Use settings from first dataset
        self.attributes = self.datasets[0].attributes
        self.ring = ring
        self.use_r1_min = use_r1_min
        self.max_neighbors = self.datasets[0].max_neighbors
        self.feature_dim = self.datasets[0].feature_dim
        self.features_entry_size = self.datasets[0].features_entry_size
        
        print(f"\nCombined dataset created:")
        print(f"  Total sources: {len(self.datasets)}")
        print(f"  Total examples: {self.total_length}")
        for name, ds, weight in zip(self.dataset_names, self.datasets, self.dataset_weights):
            print(f"    - {name}: {len(ds)} examples (weight={weight})")
    
    def __len__(self) -> int:
        return self.total_length
    
    def __getitem__(self, idx) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        # Find which dataset this index belongs to
        for i, (start, end) in enumerate(zip(self.cumulative_lengths[:-1], self.cumulative_lengths[1:])):
            if start <= idx < end:
                local_idx = idx - start
                return self.datasets[i][local_idx]
        raise IndexError(f"Index {idx} out of range for combined dataset of size {self.total_length}")
    
    def get_sample_weights(self) -> torch.Tensor:
        """
        Get sample weights for WeightedRandomSampler.
        
        Each sample's weight is determined by its source dataset's weight.
        This allows oversampling from smaller datasets or undersampling from larger ones.
        
        Returns:
            Tensor of weights, one per sample
        """
        weights = []
        for i, ds in enumerate(self.datasets):
            ds_weight = self.dataset_weights[i]
            weights.extend([ds_weight] * len(ds))
        return torch.tensor(weights, dtype=torch.float64)
    
    def get_source_index(self, idx: int) -> int:
        """Get which source dataset an index belongs to."""
        for i, (start, end) in enumerate(zip(self.cumulative_lengths[:-1], self.cumulative_lengths[1:])):
            if start <= idx < end:
                return i
        raise IndexError(f"Index {idx} out of range")
    
    def print_info(self):
        """Print combined dataset information."""
        print("="*80)
        print("Combined Gaussian Patch Dataset Information")
        print("="*80)
        print(f"Total sources: {len(self.datasets)}")
        print(f"Total examples: {self.total_length}")
        print(f"Ring: {self.ring}")
        print(f"Attributes: {self.attributes}")
        print(f"Max neighbors: {self.max_neighbors}")
        print(f"Feature dimension: {self.feature_dim}")
        print()
        print("Individual datasets:")
        for name, ds, weight in zip(self.dataset_names, self.datasets, self.dataset_weights):
            print(f"\n  {name} (weight={weight}):")
            print(f"    Examples: {len(ds)}")
            if ds.metadata and 'surface' in ds.metadata:
                print(f"    Surface: {ds.metadata['surface'].get('name', 'Unknown')}")
                print(f"    Texture: {ds.metadata['surface'].get('texture', 'Unknown')}")
        print("="*80)


def create_combined_dataloaders(
    config: Union[str, Path, List[Union[str, Path]]],
    attributes: List[str],
    ring: int,
    use_r1_min: bool,
    batch_size: int = 32,
    train_split: float = 0.8,
    num_workers: int = 4,
    seed: int = 42,
    transform: Optional[callable] = None,
    use_weighted_sampling: bool = False
) -> Tuple[torch.utils.data.DataLoader, torch.utils.data.DataLoader]:
    """
    Create train and validation dataloaders from a combined dataset config.
    
    Args:
        config: Either:
            - Path to multi-source config YAML file
            - List of paths to individual config YAML files
        attributes: List of attributes to include
        ring: Ring number to load
        use_r1_min: Whether to include r1_min values
        batch_size: Batch size for dataloaders
        train_split: Fraction of data for training
        num_workers: Number of worker processes
        seed: Random seed for split
        transform: Optional transform
        use_weighted_sampling: If True, use WeightedRandomSampler with source weights
    
    Returns:
        Tuple of (train_loader, val_loader)
    """
    dataset = CombinedGaussianPatchDataset(
        config=config,
        attributes=attributes,
        ring=ring,
        use_r1_min=use_r1_min,
        transform=transform
    )
    
    dataset_size = len(dataset)
    train_size = int(train_split * dataset_size)
    val_size = dataset_size - train_size
    
    train_dataset, val_dataset = torch.utils.data.random_split(
        dataset,
        [train_size, val_size],
        generator=torch.Generator().manual_seed(seed)
    )
    
    import warnings
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="CUDA initialization")
        use_pin_memory = torch.cuda.is_available()
    
    # Create samplers based on whether weighted sampling is requested
    if use_weighted_sampling and len(dataset.datasets) > 1:
        # Get weights for the full dataset
        full_weights = dataset.get_sample_weights()
        # Get weights for training indices only
        train_indices = train_dataset.indices
        train_weights = full_weights[train_indices]
        
        train_sampler = torch.utils.data.WeightedRandomSampler(
            weights=train_weights,
            num_samples=len(train_dataset),
            replacement=True
        )
        
        train_loader = torch.utils.data.DataLoader(
            train_dataset,
            batch_size=batch_size,
            sampler=train_sampler,
            num_workers=num_workers,
            pin_memory=use_pin_memory
        )
    else:
        train_loader = torch.utils.data.DataLoader(
            train_dataset,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=use_pin_memory
        )
    
    val_loader = torch.utils.data.DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=use_pin_memory
    )
    
    return train_loader, val_loader


def create_dataloaders(
    config_path: Union[str, Path] = None,
    config: Union[str, Path] = None,
    attributes: List[str] = None,
    ring: int = 2,
    use_r1_min: bool = False,
    batch_size: int = 32,
    train_split: float = 0.8,
    num_workers: int = 4,
    seed: int = 42,
    transform: Optional[callable] = None
) -> Tuple[torch.utils.data.DataLoader, torch.utils.data.DataLoader]:
    """
    Create train and validation dataloaders from Gaussian patch data.
    
    For multi-source configs, use create_combined_dataloaders instead.
    
    Args:
        config_path: DEPRECATED. Use 'config' instead. Path to config YAML file.
        config: Path to config YAML file (required)
        attributes: List of attributes to include (must be subset of config attributes)
        ring: Ring number to load
        use_r1_min: Whether to include r1_min values
        batch_size: Batch size for dataloaders
        train_split: Fraction of data to use for training (rest for validation)
        num_workers: Number of worker processes for data loading
        seed: Random seed for train/val split
        transform: Optional transform to apply to features
    
    Returns:
        Tuple of (train_loader, val_loader)
    """
    # Handle both config_path (legacy) and config (new) parameters
    if config is None and config_path is None:
        raise ValueError("Either 'config' or 'config_path' must be provided")
    config_input = config if config is not None else config_path
    
    # Create full dataset
    dataset = GaussianPatchDataset(
        config=config_input,
        attributes=attributes,
        ring=ring,
        use_r1_min=use_r1_min,
        transform=transform
    )
    
    # Split into train and validation
    dataset_size = len(dataset)
    train_size = int(train_split * dataset_size)
    val_size = dataset_size - train_size
    
    train_dataset, val_dataset = torch.utils.data.random_split(
        dataset,
        [train_size, val_size],
        generator=torch.Generator().manual_seed(seed)
    )
    
    # Create dataloaders
    # Only use pin_memory if CUDA is available (suppress warning if CUDA init fails)
    import warnings
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="CUDA initialization")
        use_pin_memory = torch.cuda.is_available()
    
    train_loader = torch.utils.data.DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=use_pin_memory
    )
    
    val_loader = torch.utils.data.DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=use_pin_memory
    )
    
    return train_loader, val_loader


