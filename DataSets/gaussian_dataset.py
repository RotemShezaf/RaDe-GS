class GaussianPatchDataset(Dataset):
    """
    Dataset for loading Gaussian training patches from config file or dict.
    
    Each example consists of:
    - Neighbor features (flattened): positions, and optionally normals, euclidean distances, 
      opacity, rotation, SH features
    - Target geodesic distance (p_u): the distance value to predict (second to last value)
    - Ring-1 minimum distance (r1_min_val): for dropout augmentation (last value)
    - Valid mask: boolean mask indicating which neighbors are valid (not masked/padded)
    
    The dataset loads data from a single ring level.
    """
    
    def __init__(
        self,
        config_path: Union[str, Path, Dict] = None,
        config: Union[str, Path, Dict] = None,
        attributes: List[str] = None,
        ring: int = 2,
        use_r1_min: bool = False,
        transform: Optional[callable] = None,
        lazy_loading: bool = False,
        inference_only: bool = False,
        normalize_all_neighbors: Optional[bool] = None,
    ):
        """
        Initialize the Gaussian patch dataset.
        
        Args:
            config_path: DEPRECATED. Use 'config' instead. Path to config YAML file or config dict.
            config: Path to config YAML file OR config dict (for in-memory configs from CombinedGaussianPatchDataset).
            attributes: List of attributes to include in the features (e.g., ["xyz", "normals"]).
                       Must be a subset of attributes in config.
            ring: Ring number to load (required).
            use_r1_min: If True, data includes r1_min_val for dropout augmentation.
            transform: Optional transform to apply to the features.
            lazy_loading: If True, use memory-mapped loading (data read from disk
                on demand per sample). Useful for very large datasets that don't
                fit in RAM. If False (default), load the entire dataset into a
                torch.Tensor in RAM at init time for fastest training.
            inference_only: If True, skip loading .npy data files. All metadata
                (feature indices, entry sizes, attribute positions) is still
                computed from the config. Use this when only get_item_from_raw
                and _denormalize_results are needed (e.g. in GaussianInputBuilder).
                When True, ring must be explicitly provided.
            normalize_all_neighbors: If True, compute max_dist for XYZ normalization
                over ALL neighbors (including padded/duplicated), not just valid ones.
                If None, reads from config key 'normalize_all_neighbors' (default False).
        """
        self.transform = transform
        # Split transforms into pre-normalization (dropout) and post-normalization.
        # Dropout transforms invalidate neighbours by setting geodesic to
        # mask_constant, so they must run BEFORE normalization so that
        # max_dist is computed only from the surviving valid neighbours.
        self._pre_norm_transform, self._post_norm_transform = self._split_transforms(transform)
        self.lazy_loading = lazy_loading
        
        # Handle both config_path (legacy) and config (new) parameters
        if config is None and config_path is None:
            raise ValueError("Either 'config' or 'config_path' must be provided")
        
        # Prefer 'config' but support 'config_path' for backward compatibility
        config_input = config if config is not None else config_path
        
        # Load config from path or use dict directly
        if isinstance(config_input, dict):
            self.config = config_input
            self._config_source = 'dict'
        else:
            config_path = Path(config_input)
            if not config_path.exists():
                raise FileNotFoundError(f"Config file not found: {config_path}")
            
            with open(config_path, 'r') as f:
                self.config = yaml.safe_load(f)
            self._config_source = str(config_path)

        # Resolve normalize_all_neighbors: explicit arg > config > False
        if normalize_all_neighbors is not None:
            self.normalize_all_neighbors = normalize_all_neighbors
        else:
            self.normalize_all_neighbors = self.config.get('normalize_all_neighbors', False)

        # Resolve mask_constant from config (always)
        self.mask_constant = float(self.config.get('mask_constant', -10.0))

        # Get data directory from config
        if 'output_dir' not in self.config:
            raise ValueError("Config file must contain 'output_dir' field")
        data_dir = self.config['output_dir']
        
        # Get config attributes
        config_attributes = self.config.get('attributes', ['xyz'])
        
        # Assert that requested attributes are in config attributes
        if attributes is None:
            # Exclude internal-only attributes (prefixed with _) from default
            attributes = [a for a in config_attributes if not a.startswith('_')]
        for attr in attributes:
            assert attr in config_attributes, \
                f"Attribute '{attr}' not found in config attributes: {config_attributes}"
        
        # Assert use_r1_min is consistent with config if specified in config
        if 'use_r1_min_val' in self.config:
            config_use_r1_min = self.config['use_r1_min_val']
            assert use_r1_min == config_use_r1_min or not use_r1_min, \
                f"use_r1_min={use_r1_min} conflicts with config use_r1_min_val={config_use_r1_min}. " \
                f"Can only request use_r1_min=True if config has use_r1_min_val=True"
            if use_r1_min and not config_use_r1_min:
                raise ValueError("Cannot use use_r1_min=True when config has use_r1_min_val=False")
        
        # Store settings
        self.attributes = attributes
        self.config_attributes = config_attributes
        self.use_r1_min = use_r1_min
        self.ring = ring
        self.data_dir = Path(data_dir)
        self.surface_type = self.config.get('surface_type', None)
        
        # Get neighborhood info
        use_mahalanobis = self.config.get('use_mahalanobis', False)
        neighborhood_method = 'mahalanobis' if use_mahalanobis else 'euclidean'
        if 'ring_size_mapping' in self.config and neighborhood_method in self.config['ring_size_mapping']:
            self.max_neighbors = self.config['ring_size_mapping'][neighborhood_method][ring]
        else:
            raise ValueError(f"ring_size_mapping for {neighborhood_method} not found in config")
        
        # Load metadata if available
        self.metadata = None
        metadata_path = self.data_dir / 'generation_metadata.json'
        if metadata_path.exists():
            with open(metadata_path, 'r') as f:
                self.metadata = json.load(f)
        
        # Load data for the specified ring (skipped in inference_only mode)
        self.inference_only = inference_only
        if inference_only:
            if ring is None:
                raise ValueError("ring must be provided when inference_only=True")
            self.examples = None
            self.ring_info = {}
        else:
            self.examples, self.ring_info = self._load_data()

        # Calculate indices to extract instead of modifying data
        self._calculate_feature_indices()
        
        self.features_entry_size = self._get_entry_size(self.attributes)
        
        self.feature_dim = self._get_feature_dim()
        
    def _load_data(self) -> Tuple[Union[torch.Tensor, np.ndarray], Dict]:
        """
        Load .npy file for the specified ring from the data directory.
        
        When ``lazy_loading`` is True, uses memory-mapped loading
        (``mmap_mode='r'``) so the full dataset is **not** read into RAM
        and individual rows are fetched from disk on demand.  This is
        useful for very large datasets that do not fit in RAM.
        
        When ``lazy_loading`` is False (the default), the file is read
        entirely into a ``torch.Tensor`` in RAM at init time.  This gives
        the fastest training throughput because every ``__getitem__`` call
        is a pure in-memory operation.
        
        Returns:
            Tuple of (examples, ring_info_dict)
                examples: torch.Tensor (eager) or np.memmap (lazy)
        """
        data_files = sorted(self.data_dir.glob('gaussian_examples_ring*.npy'))
        
        if len(data_files) == 0:
            raise FileNotFoundError(
                f"No data files matching 'gaussian_examples_ring*.npy' found in {self.data_dir}"
            )
        
        # Find the file for the requested ring or use first available
        target_file = None
        
        if self.ring is not None:
            # Look for specific ring
            for file_path in data_files:
                filename = file_path.stem
                parts = filename.split('_')
                ring_idx = next(i for i, p in enumerate(parts) if p.startswith('ring'))
                ring_num = int(parts[ring_idx].replace('ring', ''))
                
                if ring_num == self.ring:
                    target_file = file_path
                    break
            
            if target_file is None:
                raise FileNotFoundError(
                    f"No data file found for ring {self.ring} in {self.data_dir}"
                )
        else:
            # Use first available ring
            target_file = data_files[0]
            filename = target_file.stem
            parts = filename.split('_')
            ring_idx = next(i for i, p in enumerate(parts) if p.startswith('ring'))
            self.ring = int(parts[ring_idx].replace('ring', ''))
        
        if self.lazy_loading:
            # Memory-mapped load – data stays on disk until accessed
            examples = np.load(target_file, mmap_mode='r')
            load_mode = 'memory-mapped'
        else:
            # Eager load – read entire file into RAM as a torch.Tensor
            examples_np = np.load(target_file)
            examples = torch.from_numpy(examples_np).float()
            load_mode = 'eager'
        
        ring_info = {
            'shape': tuple(examples.shape),
            'num_examples': len(examples),
            'feature_size': examples.shape[1] - 2 if self.use_r1_min else examples.shape[1] - 1,
            'file_path': target_file
        }
        
        print(f"Loaded ring {self.ring}: {len(examples)} examples from {target_file.name} ({load_mode})")
        
        return examples, ring_info
    
    def _get_entry_size(self, attributes: List[str]) -> int:
        """
        Calculate the size of a single Gaussian entry with given attributes.
        
        Args:
            attributes: List of attribute names
            
        Returns:
            Size in number of features (including geodesic distance)
        """
        entry_size = sum([
            4 if attr == "rotation" else 
            3 if attr in ["xyz", "normals", "scale", "sh", "_aug_normals"] else 
            1 for attr in attributes
        ])
        return entry_size + 1  # +1 for geodesic distance
    
    def _calculate_feature_indices(self):
        """
        Calculate indices to extract from examples based on requested attributes.
        Stores these indices for use in __getitem__.
        """
        # Calculate entry sizes
        config_entry_size = self._get_entry_size(self.config_attributes)
        target_entry_size = self._get_entry_size(self.attributes)
        
        # Calculate indices to keep for each neighbor
        indices_to_keep = []
        config_idx = 0
        
        for config_attr in self.config_attributes:
            if config_attr in self.attributes:
                # This attribute is requested, keep its indices
                if config_attr == "rotation":
                    indices_to_keep.extend(range(config_idx, config_idx + 4))
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh"]:
                    indices_to_keep.extend(range(config_idx, config_idx + 3))
                    config_idx += 3
                else:
                    indices_to_keep.append(config_idx)
                    config_idx += 1
            else:
                # Skip this attribute
                if config_attr == "rotation":
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh", "_aug_normals"]:
                    config_idx += 3
                else:
                    config_idx += 1
        
        # Add geodesic distance index (last in entry)
        indices_to_keep.append(config_entry_size - 1)
        
        # Store indices for neighbors (replicated for each neighbor)
        self.neighbor_indices = []
        for neighbor_idx in range(self.max_neighbors):
            start_idx = neighbor_idx * config_entry_size
            for rel_idx in indices_to_keep:
                self.neighbor_indices.append(start_idx + rel_idx)
        
        # Calculate indices for point features (no geodesic distance)
        point_start_idx = self.max_neighbors * config_entry_size
        point_entry_size = config_entry_size - 1
        
        point_indices_to_keep = []
        config_idx = 0
        
        for config_attr in self.config_attributes:
            if config_attr in self.attributes:
                if config_attr == "rotation":
                    point_indices_to_keep.extend(range(config_idx, config_idx + 4))
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh", "_aug_normals"]:
                    point_indices_to_keep.extend(range(config_idx, config_idx + 3))
                    config_idx += 3
                else:
                    point_indices_to_keep.append(config_idx)
                    config_idx += 1
            else:
                if config_attr == "rotation":
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh", "_aug_normals"]:
                    config_idx += 3
                else:
                    config_idx += 1
        
        # Store indices for point features
        self.point_indices = [point_start_idx + rel_idx for rel_idx in point_indices_to_keep]
        
        # Store whether to use r1_min_val
        self.has_r1_min_in_data = 'use_r1_min_val' in self.config and self.config['use_r1_min_val']
        
        # Calculate attribute positions within extracted features for normalization
        self._calculate_attribute_positions()
        
        # ── _aug_normals extraction indices (separate from model features) ──
        self._has_aug_normals = '_aug_normals' in self.config_attributes
        self._aug_normals_neighbor_indices = []
        self._aug_normals_point_indices = []
        if self._has_aug_normals:
            # Find offset of _aug_normals within a single config entry
            aug_off = 0
            for ca in self.config_attributes:
                if ca == '_aug_normals':
                    break
                if ca == 'rotation':
                    aug_off += 4
                elif ca in ['xyz', 'normals', 'scale', 'sh']:
                    aug_off += 3
                else:
                    aug_off += 1
            # Neighbor indices (one block of 3 per neighbor)
            for ni in range(self.max_neighbors):
                base = ni * config_entry_size
                self._aug_normals_neighbor_indices.extend([
                    base + aug_off, base + aug_off + 1, base + aug_off + 2])
            # Point feature indices (entry without geodesic)
            pt_base = self.max_neighbors * config_entry_size
            self._aug_normals_point_indices = [
                pt_base + aug_off, pt_base + aug_off + 1, pt_base + aug_off + 2]
        
        print(f"Calculated feature indices: {len(self.neighbor_indices)} neighbor indices, {len(self.point_indices)} point indices"
              + (f", {len(self._aug_normals_neighbor_indices)} aug_normals indices" if self._has_aug_normals else ""))
    
    def _calculate_attribute_positions(self):
        """
        Calculate attribute positions within the extracted feature vector.
        Used for per-example normalization in __getitem__.
        Note: This works on EXTRACTED features (only requested attributes).
        """
        # Calculate size of one neighbor entry in EXTRACTED features
        entry_size_per_neighbor = sum([
            4 if attr == "rotation" else
            3 if attr in ["xyz", "normals", "scale", "sh", "_aug_normals"] else
            1 for attr in self.attributes
        ]) + 1  # +1 for geodesic distance
        
        # Calculate attribute positions
        self.attr_positions_in_features = {}
        current_offset = 0
        
        for attr in self.attributes:
            # Determine size of this attribute
            if attr == "rotation":
                attr_size = 4
            elif attr in ["xyz", "normals", "scale", "sh", "_aug_normals"]:
                attr_size = 3
            else:
                attr_size = 1
            
            # Calculate positions in neighbor features
            neighbor_positions = []
            for neighbor_idx in range(self.max_neighbors):
                neighbor_base = neighbor_idx * entry_size_per_neighbor
                neighbor_positions.extend(range(
                    neighbor_base + current_offset,
                    neighbor_base + current_offset + attr_size
                ))
            
            # Calculate positions in point features (no geodesic distance)
            point_entry_size = entry_size_per_neighbor - 1  # No geodesic in point features
            point_base = self.max_neighbors * entry_size_per_neighbor
            point_positions = list(range(
                point_base + current_offset,
                point_base + current_offset + attr_size
            ))
            
            self.attr_positions_in_features[attr] = {
                'neighbor_positions': neighbor_positions,
                'point_positions': point_positions,
                'size': attr_size
            }
            
            current_offset += attr_size
    
    def _remove_r1_min_val(self):
        """
        Remove r1_min_val column from examples if use_r1_min is False.
        
        This modifies self.examples in-place to remove the second-to-last column.
        """
        # Remove second-to-last column (r1_min_val)
        # Keep all columns except the second-to-last
        self.examples = torch.cat([self.examples[:, :-2], self.examples[:, -1:]], dim=1)
        print(f"Removed r1_min_val column. New shape: {self.examples.shape}")
    
    def _get_feature_dim(self) -> int:
        """Get the feature dimension (excluding target values)."""
        # Feature dim is the number of neighbor indices + point indices
        return len(self.neighbor_indices) + len(self.point_indices)
    
    def __len__(self) -> int:
        """Return the number of examples in the dataset."""
        return len(self.examples)
    
    def __getitem__(self, idx) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Get a single training example.
        
        Args:
            idx: Index of the example to retrieve
        
        Returns:
            Tuple of (neighborhood, point_features, target, valid_mask)
            
            Where:
            - neighborhood: (max_neighbors, entry_size) tensor of neighbor features
            - point_features: (point_feature_size,) tensor of point features
            - target: scalar tensor of geodesic distance (label)
            - valid_mask: (max_neighbors,) boolean tensor, True for valid neighbors, False for masked/padded
        """
        # When lazy_loading is True self.examples is an np.memmap – read
        # a single row from disk and convert to a float32 tensor.
        # When lazy_loading is False self.examples is already a torch.Tensor
        # in RAM so this is a simple indexing operation.
        if self.lazy_loading:
            example = torch.from_numpy(np.array(self.examples[idx])).float()
        else:
            example = self.examples[idx]
        
        # Extract neighbor features using precomputed indices
        neighbor_features = example[self.neighbor_indices]
        
        # Extract point features using precomputed indices
        point_features = example[self.point_indices]
        
        # Reshape neighborhood to (max_neighbors, entry_size)
        entry_size = self.features_entry_size
        neighborhood = neighbor_features.view(self.max_neighbors, entry_size)

        # Extract target (p_u) and r1_min_val before normalization
        if self.has_r1_min_in_data:
            target = example[-1]     # p_u is last when r1_min_val exists
            r1_min_val = example[-2] # r1_min_val is second to last
        else:
            target = example[-1]     # p_u is last
            r1_min_val = None        # Not available

        # If use_r1_min is False, don't pass r1_min_val to transforms
        if not self.use_r1_min:
            r1_min_val = None

        # Extract _aug_normals (separate from model features) if available
        aug_normals = None
        if self._has_aug_normals:
            aug_normals = example[self._aug_normals_neighbor_indices].view(self.max_neighbors, 3).clone()

        # --- Stage 1: dropout transforms BEFORE normalization ---
        # Dropout sets geodesic to mask_constant for dropped neighbours,
        # so max_dist (computed during normalization) will ignore them.
        if self._pre_norm_transform is not None:
            neighborhood, point_features = self._pre_norm_transform(
                neighborhood, point_features, r1_min_val,
                surface_type=self.surface_type,
                aug_normals=aug_normals,
            )

        # --- Stage 2: normalize (opacity/sh/scale + xyz centering + max_dist scaling) ---
        neighborhood, point_features, target, r1_min_val, _norm_params = self._normalize_patches(
            neighborhood, point_features, target, r1_min_val
        )

        # --- Stage 3: remaining transforms AFTER normalization ---
        if self._post_norm_transform is not None:
            neighborhood, point_features = self._post_norm_transform(
                neighborhood, point_features, r1_min_val,
                surface_type=self.surface_type,
                aug_normals=aug_normals,
                normalize_all_neighbors=self.normalize_all_neighbors,
            )

        # Compute valid mask based on geodesic distance (last value in each neighbor entry)
        geodesic_distances = neighborhood[:, -1]  # Last value is geodesic distance
        valid_mask = geodesic_distances != self.mask_constant  # True for valid, False for masked     

        return neighborhood, point_features, target, valid_mask
    
    def _normalize_examples(self) -> torch.Tensor:
        """
        .. deprecated::
            Per-example normalization is now applied lazily inside
            ``__getitem__`` via ``_normalize_patches``.  This method is kept
            for backward compatibility and is a no-op.
        """
        print("_normalize_examples is a no-op; normalization is done in __getitem__.")
        return self.examples

    # Names of transforms that invalidate neighbours (set geodesic to
    # mask_constant) and therefore must run BEFORE xyz/max_dist normalization.
    _DROPOUT_TRANSFORM_NAMES = frozenset({
        'GaussianPatchDropout',
        'SparseContextDropout',
    })

    @staticmethod
    def _split_transforms(transform):
        """Split a transform pipeline into (pre_norm, post_norm).

        Dropout-style transforms (those in ``_DROPOUT_TRANSFORM_NAMES``)
        are placed in *pre_norm* so they execute before normalization and
        ``max_dist`` is computed only from the surviving valid neighbours.
        All other transforms go into *post_norm*.

        Returns:
            ``(pre_norm_callable_or_None, post_norm_callable_or_None)``
        """
        if transform is None:
            return None, None

        dropout_names = GaussianPatchDataset._DROPOUT_TRANSFORM_NAMES

        # Single transform (no .transforms list)
        if not hasattr(transform, 'transforms'):
            if transform.__class__.__name__ in dropout_names:
                return transform, None
            return None, transform

        # Compose – split the list
        pre = [t for t in transform.transforms if t.__class__.__name__ in dropout_names]
        post = [t for t in transform.transforms if t.__class__.__name__ not in dropout_names]

        def _to_callable(ts):
            if not ts:
                return None
            if len(ts) == 1:
                return ts[0]
            # Lightweight inline compose
            def _chain(neighborhood, point_features, r1_min_val=None, **kwargs):
                for t in ts:
                    neighborhood, point_features = t(neighborhood, point_features, r1_min_val, **kwargs)
                return neighborhood, point_features
            return _chain

        return _to_callable(pre), _to_callable(post)

    def _normalize_patches(
        self,
        neighborhood: torch.Tensor,
        point_features: torch.Tensor,
        target: Optional[torch.Tensor] = None,
        r1_min_val: Optional[torch.Tensor] = None,
    ) -> Union[
        Tuple[torch.Tensor, torch.Tensor],
        Tuple[torch.Tensor, torch.Tensor, Optional[torch.Tensor], Optional[torch.Tensor], Dict],
    ]:
        """
        Normalize a patch's features (or batch of features).

        Performs two stages of normalization:

        1. **Attribute-specific normalization** (opacity min-max, SH scaling,
           scale point-cloud normalization).
        2. **XYZ centering + max-distance scaling** (previously handled by
           ``_normalize_xyz_geodesic``): centres xyz relative to the point,
           then divides xyz and geodesic distances by the maximum Euclidean
           distance to any *real* (non-padded) neighbour.

        Works on EXTRACTED features (only requested attributes).

        Args:
            neighborhood: Neighbor features.
                Shape: ``(max_neighbors, entry_size)`` for single example, or
                ``(batch_size, max_neighbors, entry_size)`` for a batch.
            point_features: Point features.
                Shape: ``(point_feature_size,)`` or
                ``(batch_size, point_feature_size)``.
            target: Scalar (or batch of scalars) geodesic distance to
                normalize.  When provided, ``target`` and ``r1_min_val`` are
                also returned.
            r1_min_val: Optional ring-1 minimum distance (same shape as
                ``target``).

        Returns:
            * When ``target`` is ``None`` (legacy call):
              ``(neighborhood, point_features)``
            * When ``target`` is provided:
              ``(neighborhood, point_features, target, r1_min_val, norm_params)``
              where ``norm_params`` is a dict containing at least ``'max_dist'``
              (the scalar used to divide xyz and geodesic, per-example when
              batched).
        """
        import math

        legacy_return = target is None

        # Handle both single example and batch
        is_batch = neighborhood.dim() > 2
        if not is_batch:
            neighborhood = neighborhood.unsqueeze(0)  # Add batch dimension
            point_features = point_features.unsqueeze(0)
            if target is not None:
                target = target.unsqueeze(0) if target.dim() == 0 else target
            if r1_min_val is not None:
                r1_min_val = r1_min_val.unsqueeze(0) if r1_min_val.dim() == 0 else r1_min_val

        batch_size = neighborhood.shape[0]
        max_neighbors = neighborhood.shape[1]
        entry_size = neighborhood.shape[2]

        # Calculate attribute positions within entry (excluding geodesic at end)
        attr_offsets = {}
        current_offset = 0
        for attr in self.attributes:
            if attr == "rotation":
                attr_offsets[attr] = (current_offset, 4)
                current_offset += 4
            elif attr in ["xyz", "normals", "scale", "sh", "_aug_normals"]:
                attr_offsets[attr] = (current_offset, 3)
                current_offset += 3
            else:
                attr_offsets[attr] = (current_offset, 1)
                current_offset += 1

        # Normalize opacity (min-max to [0, 1]) per example
        if "opacity" in attr_offsets:
            offset, size = attr_offsets["opacity"]

            # Get all opacity values (neighbors + point) for this example
            neighbor_opacity = neighborhood[:, :, offset:offset + size]  # (batch, max_neighbors, 1)
            point_opacity = point_features[:, offset:offset + size]       # (batch, 1)

            all_opacity = torch.cat([
                neighbor_opacity.view(batch_size, -1),
                point_opacity
            ], dim=-1)

            opacity_min = all_opacity.min(dim=-1, keepdim=True)[0]  # (batch_size, 1)
            opacity_max = all_opacity.max(dim=-1, keepdim=True)[0]  # (batch_size, 1)

            opacity_range = opacity_max - opacity_min
            opacity_range = torch.where(opacity_range > 0, opacity_range, torch.ones_like(opacity_range))

            # Normalize neighbor opacity
            neighborhood[:, :, offset:offset + size] = (
                (neighbor_opacity - opacity_min.unsqueeze(-1)) / opacity_range.unsqueeze(-1)
            )
            # Normalize point opacity
            point_features[:, offset:offset + size] = (point_opacity - opacity_min) / opacity_range

        # Normalize SH features (transformation)
        if "sh" in attr_offsets:
            offset, size = attr_offsets["sh"]

            # Apply transformation to neighbors
            neighborhood[:, :, offset:offset + size] = (
                neighborhood[:, :, offset:offset + size] * 0.28209479177387814
            )
            neighborhood[:, :, offset:offset + size] = torch.clamp(
                neighborhood[:, :, offset:offset + size], -0.5, 0.5
            )
            neighborhood[:, :, offset:offset + size] = (
                2 * neighborhood[:, :, offset:offset + size] / math.sqrt(3)
            )

            # Apply transformation to point
            point_features[:, offset:offset + size] = (
                point_features[:, offset:offset + size] * 0.28209479177387814
            )
            point_features[:, offset:offset + size] = torch.clamp(
                point_features[:, offset:offset + size], -0.5, 0.5
            )
            point_features[:, offset:offset + size] = (
                2 * point_features[:, offset:offset + size] / math.sqrt(3)
            )

        # Normalize scale (point cloud normalization) per example
        if "scale" in attr_offsets:
            offset, size = attr_offsets["scale"]

            # Get scale values
            neighbor_scales = neighborhood[:, :, offset:offset + size]  # (batch, max_neighbors, 3)
            point_scale = point_features[:, offset:offset + size].unsqueeze(1)  # (batch, 1, 3)
            all_scales = torch.cat([neighbor_scales, point_scale], dim=1)  # (batch, max_neighbors+1, 3)

            # Compute centroid
            centroid = all_scales.mean(dim=1, keepdim=True)  # (batch_size, 1, 3)

            # Center the data
            scales_centered = all_scales - centroid  # (batch_size, max_neighbors + 1, 3)

            # Compute max distance from origin
            distances = torch.sqrt(torch.sum(scales_centered ** 2, dim=2))  # (batch_size, max_neighbors + 1)
            m = distances.max(dim=1, keepdim=True)[0].unsqueeze(-1)  # (batch_size, 1, 1)

            # Normalize
            scales_normalized = torch.where(
                m > 0,
                scales_centered / m,
                scales_centered
            )

            # Update neighborhood and point features
            neighborhood[:, :, offset:offset + size] = scales_normalized[:, :max_neighbors]
            point_features[:, offset:offset + size] = scales_normalized[:, -1]

        # ──────────────────────────────────────────────────────────────────
        # XYZ centering + max-distance scaling
        # (previously in _normalize_xyz_geodesic)
        # ──────────────────────────────────────────────────────────────────
        # Collect per-sample max_dist for norm_params.
        max_dist_per_sample = torch.ones(batch_size, device=neighborhood.device)

        if "xyz" in attr_offsets:
            xyz_offset, _ = attr_offsets["xyz"]
            geodesic_idx = self.features_entry_size - 1  # last col = geodesic

            for b in range(batch_size):
                nbhd = neighborhood[b]           # (max_neighbors, entry_size)
                pf   = point_features[b]         # (point_feature_size,)

                # real_mask: rows with valid xyz (legacy check for old-format
                # data where padded entries had mask_constant in xyz).
                real_mask = nbhd[:, xyz_offset] != self.mask_constant
                # geo_valid: rows with a known geodesic distance (i.e. truly
                # valid neighbors, NOT padded duplicates).  Used to compute
                # max_dist so that duplicated padding does not affect the
                # distance scale.
                # NOTE: Dropout transforms (GaussianPatchDropout,
                # SparseContextDropout) now run BEFORE normalization, so
                # geo_valid already excludes dropped neighbours and max_dist
                # reflects only the surviving valid set.
                geo_valid = nbhd[:, geodesic_idx] != self.mask_constant

                if not geo_valid.any():
                    # Fall back to real_mask if no geo_valid (shouldn't happen
                    # in practice, but guard against degenerate patches).
                    if not real_mask.any():
                        continue
                    geo_valid_for_dist = real_mask
                elif self.normalize_all_neighbors:
                    # Use ALL non-padded neighbors (including duplicated padding
                    # with valid xyz) for max_dist computation.
                    geo_valid_for_dist = real_mask
                else:
                    geo_valid_for_dist = geo_valid

                # 1) Centre xyz by the point's position (apply to all real
                #    entries so padded duplicates stay in the same frame)
                point_xyz = pf[xyz_offset:xyz_offset + 3].clone()
                nbhd[real_mask, xyz_offset:xyz_offset + 3] -= point_xyz
                pf[xyz_offset:xyz_offset + 3] = 0.0

                # 2) Scale by max Euclidean distance to any VALID neighbour
                dists = torch.norm(nbhd[geo_valid_for_dist, xyz_offset:xyz_offset + 3], dim=1)
                max_dist = dists.max().clamp(min=1e-8)
                max_dist_per_sample[b] = max_dist

                nbhd[real_mask, xyz_offset:xyz_offset + 3] /= max_dist
                nbhd[geo_valid, geodesic_idx] /= max_dist

                neighborhood[b] = nbhd
                point_features[b] = pf

            if target is not None:
                if target.dim() == 0:
                    target = target / max_dist_per_sample[0]
                else:
                    target = target / max_dist_per_sample

                if r1_min_val is not None:
                    if r1_min_val.dim() == 0:
                        r1_min_val = r1_min_val / max_dist_per_sample[0]
                    else:
                        r1_min_val = r1_min_val / max_dist_per_sample

        norm_params = {'max_dist': max_dist_per_sample if batch_size > 1 else max_dist_per_sample[0]}

        # Remove batch dimension if input was single example
        if not is_batch:
            neighborhood = neighborhood.squeeze(0)
            point_features = point_features.squeeze(0)
            if target is not None:
                target = target.squeeze(0) if target.dim() > 0 else target
            if r1_min_val is not None:
                r1_min_val = r1_min_val.squeeze(0) if r1_min_val.dim() > 0 else r1_min_val
            norm_params = {'max_dist': max_dist_per_sample[0]}

        if legacy_return:
            return neighborhood, point_features
        return neighborhood, point_features, target, r1_min_val, norm_params

    def _denormalize_results(
        self,
        neighborhood: torch.Tensor,
        point_features: torch.Tensor,
        target: torch.Tensor,
        norm_params: Dict,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Invert ``_normalize_patches``.

        Reverses the xyz-centering + max-distance scaling applied during
        ``_normalize_patches``.  This is **step one** of the two-step
        inference denormalization pipeline; it should be followed by
        :func:`DataSets.utils.training_patches_helpers.denormalize_neighborhood`
        to also undo the offline per-patch scale + geodesic shift.

        Args:
            neighborhood: ``(max_neighbors, entry_size)`` normalized
                neighborhood tensor.
            point_features: ``(point_feature_size,)`` normalized point-feature
                tensor.
            target: Scalar normalized prediction (model output).
            norm_params: Dict returned by ``_normalize_patches``, must contain
                ``'max_dist'`` (scalar tensor or float).

        Returns:
            ``(neighborhood, point_features, target)`` with xyz and geodesic
            distances rescaled back by ``max_dist``.  When ``"xyz"`` is not
            among ``self.attributes``, tensors are returned unchanged.
        """
        if "xyz" not in self.attributes:
            return neighborhood, point_features, target

        max_dist = norm_params['max_dist']
        if isinstance(max_dist, torch.Tensor):
            max_dist = max_dist.item()

        # Locate xyz and geodesic columns
        xyz_offset = 0
        for attr in self.attributes:
            if attr == "xyz":
                break
            xyz_offset += {"rotation": 4, "normals": 3, "scale": 3, "sh": 3, "_aug_normals": 3}.get(attr, 1)
        geodesic_idx = self.features_entry_size - 1

        neighborhood = neighborhood.clone()
        point_features = point_features.clone()

        real_mask = neighborhood[:, xyz_offset] != self.mask_constant
        geo_valid = neighborhood[:, geodesic_idx] != self.mask_constant

        neighborhood[real_mask, xyz_offset:xyz_offset + 3] *= max_dist
        neighborhood[geo_valid, geodesic_idx] *= max_dist
        target = target * max_dist

        return neighborhood, point_features, target

    def get_item_from_raw(
        self,
        raw_example: Union[np.ndarray, torch.Tensor],
        return_norm_params: bool = False,
    ) -> Union[Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
               Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, Dict]]:
        """
        Process a raw training-example array through the full normalization
        pipeline, exactly as ``__getitem__`` does for ``self.examples[idx]``.

        This allows the inference-time ``GaussianInputBuilder`` to feed a raw
        example produced by
        :func:`DataSets.utils.training_patches_helpers.create_train_example`
        directly into the model without going through the on-disk dataset
        loading path.

        Args:
            raw_example: 1-D flat array (same layout as rows in the ``.npy``
                dataset files) or a ``torch.Tensor`` of the same shape.
            return_norm_params: If True, return a 5-tuple
                ``(neighborhood, point_features, target, valid_mask, norm_params)``
                where ``norm_params`` is the dict from ``_normalize_patches``
                (contains at least ``'max_dist'``). Useful for inference-time
                denormalization in ``GaussianInputBuilder``.

        Returns:
            ``(neighborhood, point_features, target, valid_mask)`` — the same
            four-tuple returned by ``__getitem__``.  When ``return_norm_params``
            is ``True``, a fifth element ``norm_params`` is appended.
        """
        if isinstance(raw_example, np.ndarray):
            example = torch.from_numpy(raw_example).float()
        else:
            example = raw_example.float() if raw_example.dtype != torch.float32 else raw_example

        # Extract neighbor features using precomputed indices
        neighbor_features = example[self.neighbor_indices]
        # Extract point features using precomputed indices
        point_features = example[self.point_indices]
        # Reshape neighborhood to (max_neighbors, entry_size)
        neighborhood = neighbor_features.view(self.max_neighbors, self.features_entry_size)

        # Extract target and r1_min_val
        if self.has_r1_min_in_data:
            target = example[-1]
            r1_min_val = example[-2]
        else:
            target = example[-1]
            r1_min_val = None
        if not self.use_r1_min:
            r1_min_val = None

        # Stage 1: dropout transforms before normalization
        if self._pre_norm_transform is not None:
            neighborhood, point_features = self._pre_norm_transform(
                neighborhood, point_features, r1_min_val
            )

        # Stage 2: normalization (attribute-specific + xyz centering + max_dist)
        neighborhood, point_features, target, r1_min_val, _norm_params = self._normalize_patches(
            neighborhood, point_features, target, r1_min_val
        )

        # Stage 3: remaining transforms after normalization
        if self._post_norm_transform is not None:
            neighborhood, point_features = self._post_norm_transform(
                neighborhood, point_features, r1_min_val
            )

        # Compute valid mask (geodesic != mask_constant)
        geodesic_distances = neighborhood[:, -1]
        valid_mask = geodesic_distances != self.mask_constant

        if return_norm_params:
            return neighborhood, point_features, target, valid_mask, _norm_params
        return neighborhood, point_features, target, valid_mask


        """
        Centre xyz coordinates by the point's position and scale xyz +
        geodesic distances so the patch roughly fits in a unit sphere.

        This makes the regression target (geodesic distance) commensurate
        with the spatial features, dramatically helping learning.

        Only active when ``"xyz"`` is among the requested attributes.

        Normalization uses ALL neighbours that carry real spatial data
        (including those whose geodesic distance has been masked because
        they lie beyond p_u).  This ensures that ``max_dist`` reflects the
        true spatial extent of the ring-k neighbourhood regardless of how
        many neighbours have known geodesic distances — matching the
        situation during Fast Marching inference where only a few neighbours
        may be visited but all neighbours' positions are available.

        Args:
            neighborhood:   (max_neighbors, entry_size)
            point_features: (point_feature_dim,)
            target:         scalar tensor
            r1_min_val:     scalar tensor or None

        Returns:
            (neighborhood, point_features, target, r1_min_val) – all normalised.
        """
        if "xyz" not in self.attributes:
            return neighborhood, point_features, target, r1_min_val

        # ── locate xyz columns inside the entry ──────────────────────
        xyz_offset = 0
        for attr in self.attributes:
            if attr == "xyz":
                break
            xyz_offset += {"rotation": 4, "normals": 3, "scale": 3, "sh": 3, "_aug_normals": 3}.get(attr, 1)

        geodesic_idx = self.features_entry_size - 1  # last col = geodesic dist

        # "real" neighbours have actual spatial data (xyz != mask_constant).
        # This includes both valid (known geodesic) and beyond-p_u (masked
        # geodesic but real xyz) entries.  Fully-padded rows have
        # xyz == mask_constant.
        real_mask = neighborhood[:, xyz_offset] != self.mask_constant
        # Subset of real neighbours that also have a valid geodesic distance.
        geo_valid = neighborhood[:, geodesic_idx] != self.mask_constant

        if not real_mask.any():
            return neighborhood, point_features, target, r1_min_val

        # 1) Centre xyz by the point's position
        point_xyz = point_features[xyz_offset:xyz_offset + 3].clone()
        neighborhood[real_mask, xyz_offset:xyz_offset + 3] -= point_xyz
        point_features[xyz_offset:xyz_offset + 3] = 0.0

        # 2) Scale by the max Euclidean distance to any REAL neighbour
        #    (includes beyond-p_u entries so the scale is stable)
        dists = torch.norm(neighborhood[real_mask, xyz_offset:xyz_offset + 3], dim=1)
        max_dist = dists.max().clamp(min=1e-8)

        # Normalize xyz for ALL real neighbours
        neighborhood[real_mask, xyz_offset:xyz_offset + 3] /= max_dist
        # Normalize geodesic only for entries with valid (non-masked) geodesic
        neighborhood[geo_valid, geodesic_idx] /= max_dist
        target = target / max_dist
        if r1_min_val is not None:
            r1_min_val = r1_min_val / max_dist

        return neighborhood, point_features, target, r1_min_val

