#!/usr/bin/env python3
"""
PyTorch Dataset for Gaussian training patches generated by create_gaussian_training_patches.py

This dataset loads precomputed training examples for geodesic distance prediction
on Gaussian splats. Each example contains neighbor features and target geodesic distances.
"""

import numpy as np
import torch
from torch.utils.data import Dataset
from pathlib import Path
from typing import Union, List, Optional, Tuple, Dict
import json
import yaml


class GaussianPatchDataset(Dataset):
    """
    Dataset for loading Gaussian training patches from config file.
    
    Each example consists of:
    - Neighbor features (flattened): positions, and optionally normals, euclidean distances, 
      opacity, rotation, SH features
    - Target geodesic distance (p_u): the distance value to predict (second to last value)
    - Ring-1 minimum distance (r1_min_val): for dropout augmentation (last value)
    
    The dataset loads data from a single ring level.
    """
    
    def __init__(
        self,
        config_path: Union[str, Path],
        attributes: List[str] = None,
        ring: int = 2,
        use_r1_min: bool = False,
        transform: Optional[callable] = None,
    ):
        """
        Initialize the Gaussian patch dataset.
        
        Args:
            config_path: Path to config YAML file (required).
            attributes: List of attributes to include in the features (e.g., ["xyz", "normals"]).
                       Must be a subset of attributes in config.
            ring: Ring number to load (required).
            use_r1_min: If True, data includes r1_min_val for dropout augmentation .
            transform: Optional transform to apply to the features.
        """
        self.transform = transform
        
        # Load config
        config_path = Path(config_path)
        if not config_path.exists():
            raise FileNotFoundError(f"Config file not found: {config_path}")
        
        with open(config_path, 'r') as f:
            self.config = yaml.safe_load(f)
        # Get data directory from config
        if 'output_dir' not in self.config:
            raise ValueError("Config file must contain 'output_dir' field")
        data_dir = self.config['output_dir']
        
        # Get config attributes
        config_attributes = self.config.get('attributes', ['xyz'])
        
        # Assert that requested attributes are in config attributes
        if attributes is None:
            attributes = config_attributes
        for attr in attributes:
            assert attr in config_attributes, \
                f"Attribute '{attr}' not found in config attributes: {config_attributes}"
        
        # Assert use_r1_min is consistent with config if specified in config
        if 'use_r1_min_val' in self.config:
            config_use_r1_min = self.config['use_r1_min_val']
            assert use_r1_min == config_use_r1_min or not use_r1_min, \
                f"use_r1_min={use_r1_min} conflicts with config use_r1_min_val={config_use_r1_min}. " \
                f"Can only request use_r1_min=True if config has use_r1_min_val=True"
            if use_r1_min and not config_use_r1_min:
                raise ValueError("Cannot use use_r1_min=True when config has use_r1_min_val=False")
        
        # Store settings
        self.attributes = attributes
        self.config_attributes = config_attributes
        self.use_r1_min = use_r1_min
        self.ring = ring
        self.data_dir = Path(data_dir)
        
        # Get neighborhood info
        use_mahalanobis = self.config.get('use_mahalanobis', False)
        neighborhood_method = 'mahalanobis' if use_mahalanobis else 'euclidean'
        if 'ring_size_mapping' in self.config and neighborhood_method in self.config['ring_size_mapping']:
            self.max_neighbors = self.config['ring_size_mapping'][neighborhood_method][ring]
        else:
            raise ValueError(f"ring_size_mapping for {neighborhood_method} not found in config")
        
        # Load metadata if available
        self.metadata = None
        metadata_path = self.data_dir / 'generation_metadata.json'
        if metadata_path.exists():
            with open(metadata_path, 'r') as f:
                self.metadata = json.load(f)
        
        # Load data for the specified ring
        self.examples, self.ring_info = self._load_data()
        
        # Calculate indices to extract instead of modifying data
        self._calculate_feature_indices()
        
        self.features_entry_size = self._get_entry_size(self.attributes)
        
        self.feature_dim = self._get_feature_dim()
        
    def _load_data(self) -> Tuple[torch.Tensor, Dict]:
        """
        Load .npy file for the specified ring from the data directory.
        
        Returns:
            Tuple of (examples torch tensor, ring_info_dict)
        """
        data_files = sorted(self.data_dir.glob('gaussian_examples_ring*.npy'))
        
        if len(data_files) == 0:
            raise FileNotFoundError(
                f"No data files matching 'gaussian_examples_ring*.npy' found in {self.data_dir}"
            )
        
        # Find the file for the requested ring or use first available
        target_file = None
        
        if self.ring is not None:
            # Look for specific ring
            for file_path in data_files:
                filename = file_path.stem
                parts = filename.split('_')
                ring_idx = next(i for i, p in enumerate(parts) if p.startswith('ring'))
                ring_num = int(parts[ring_idx].replace('ring', ''))
                
                if ring_num == self.ring:
                    target_file = file_path
                    break
            
            if target_file is None:
                raise FileNotFoundError(
                    f"No data file found for ring {self.ring} in {self.data_dir}"
                )
        else:
            # Use first available ring
            target_file = data_files[0]
            filename = target_file.stem
            parts = filename.split('_')
            ring_idx = next(i for i, p in enumerate(parts) if p.startswith('ring'))
            self.ring = int(parts[ring_idx].replace('ring', ''))
        
        # Load data and convert to torch tensor
        examples_np = np.load(target_file)
        examples = torch.from_numpy(examples_np).float()
        
        ring_info = {
            'shape': tuple(examples.shape),
            'num_examples': len(examples),
            'feature_size': examples.shape[1] - 2 if self.use_r1_min else examples.shape[1] - 1,
            'file_path': target_file
        }
        
        print(f"Loaded ring {self.ring}: {len(examples)} examples from {target_file.name}")
        
        return examples, ring_info
    
    def _get_entry_size(self, attributes: List[str]) -> int:
        """
        Calculate the size of a single Gaussian entry with given attributes.
        
        Args:
            attributes: List of attribute names
            
        Returns:
            Size in number of features (including geodesic distance)
        """
        entry_size = sum([
            4 if attr == "rotation" else 
            3 if attr in ["xyz", "normals", "scale", "sh"] else 
            1 for attr in attributes
        ])
        return entry_size + 1  # +1 for geodesic distance
    
    def _calculate_feature_indices(self):
        """
        Calculate indices to extract from examples based on requested attributes.
        Stores these indices for use in __getitem__.
        """
        # Calculate entry sizes
        config_entry_size = self._get_entry_size(self.config_attributes)
        target_entry_size = self._get_entry_size(self.attributes)
        
        # Calculate indices to keep for each neighbor
        indices_to_keep = []
        config_idx = 0
        
        for config_attr in self.config_attributes:
            if config_attr in self.attributes:
                # This attribute is requested, keep its indices
                if config_attr == "rotation":
                    indices_to_keep.extend(range(config_idx, config_idx + 4))
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh"]:
                    indices_to_keep.extend(range(config_idx, config_idx + 3))
                    config_idx += 3
                else:
                    indices_to_keep.append(config_idx)
                    config_idx += 1
            else:
                # Skip this attribute
                if config_attr == "rotation":
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh"]:
                    config_idx += 3
                else:
                    config_idx += 1
        
        # Add geodesic distance index (last in entry)
        indices_to_keep.append(config_entry_size - 1)
        
        # Store indices for neighbors (replicated for each neighbor)
        self.neighbor_indices = []
        for neighbor_idx in range(self.max_neighbors):
            start_idx = neighbor_idx * config_entry_size
            for rel_idx in indices_to_keep:
                self.neighbor_indices.append(start_idx + rel_idx)
        
        # Calculate indices for point features (no geodesic distance)
        point_start_idx = self.max_neighbors * config_entry_size
        point_entry_size = config_entry_size - 1
        
        point_indices_to_keep = []
        config_idx = 0
        
        for config_attr in self.config_attributes:
            if config_attr in self.attributes:
                if config_attr == "rotation":
                    point_indices_to_keep.extend(range(config_idx, config_idx + 4))
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh"]:
                    point_indices_to_keep.extend(range(config_idx, config_idx + 3))
                    config_idx += 3
                else:
                    point_indices_to_keep.append(config_idx)
                    config_idx += 1
            else:
                if config_attr == "rotation":
                    config_idx += 4
                elif config_attr in ["xyz", "normals", "scale", "sh"]:
                    config_idx += 3
                else:
                    config_idx += 1
        
        # Store indices for point features
        self.point_indices = [point_start_idx + rel_idx for rel_idx in point_indices_to_keep]
        
        # Store whether to use r1_min_val
        self.has_r1_min_in_data = 'use_r1_min_val' in self.config and self.config['use_r1_min_val']
        
        # Calculate attribute positions within extracted features for normalization
        self._calculate_attribute_positions()
        
        print(f"Calculated feature indices: {len(self.neighbor_indices)} neighbor indices, {len(self.point_indices)} point indices")
    
    def _calculate_attribute_positions(self):
        """
        Calculate attribute positions within the extracted feature vector.
        Used for per-example normalization in __getitem__.
        Note: This works on EXTRACTED features (only requested attributes).
        """
        # Calculate size of one neighbor entry in EXTRACTED features
        entry_size_per_neighbor = sum([
            4 if attr == "rotation" else
            3 if attr in ["xyz", "normals", "scale", "sh"] else
            1 for attr in self.attributes
        ]) + 1  # +1 for geodesic distance
        
        # Calculate attribute positions
        self.attr_positions_in_features = {}
        current_offset = 0
        
        for attr in self.attributes:
            # Determine size of this attribute
            if attr == "rotation":
                attr_size = 4
            elif attr in ["xyz", "normals", "scale", "sh"]:
                attr_size = 3
            else:
                attr_size = 1
            
            # Calculate positions in neighbor features
            neighbor_positions = []
            for neighbor_idx in range(self.max_neighbors):
                neighbor_base = neighbor_idx * entry_size_per_neighbor
                neighbor_positions.extend(range(
                    neighbor_base + current_offset,
                    neighbor_base + current_offset + attr_size
                ))
            
            # Calculate positions in point features (no geodesic distance)
            point_entry_size = entry_size_per_neighbor - 1  # No geodesic in point features
            point_base = self.max_neighbors * entry_size_per_neighbor
            point_positions = list(range(
                point_base + current_offset,
                point_base + current_offset + attr_size
            ))
            
            self.attr_positions_in_features[attr] = {
                'neighbor_positions': neighbor_positions,
                'point_positions': point_positions,
                'size': attr_size
            }
            
            current_offset += attr_size
    
    def _remove_r1_min_val(self):
        """
        Remove r1_min_val column from examples if use_r1_min is False.
        
        This modifies self.examples in-place to remove the second-to-last column.
        """
        # Remove second-to-last column (r1_min_val)
        # Keep all columns except the second-to-last
        self.examples = torch.cat([self.examples[:, :-2], self.examples[:, -1:]], dim=1)
        print(f"Removed r1_min_val column. New shape: {self.examples.shape}")
    
    def _get_feature_dim(self) -> int:
        """Get the feature dimension (excluding target values)."""
        # Feature dim is the number of neighbor indices + point indices
        return len(self.neighbor_indices) + len(self.point_indices)
    
    def __len__(self) -> int:
        """Return the number of examples in the dataset."""
        return len(self.examples)
    
    def __getitem__(self, idx) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Get a single training example.
        
        Args:
            idx: Index of the example to retrieve
        
        Returns:
            Tuple of (features, target)
            
            Where:
            - features: (feature_dim,) tensor of neighbor and point features
            - target: scalar tensor of geodesic distance (label)
        """
        example = self.examples[idx]
        
        # Extract neighbor features using precomputed indices
        neighbor_features = example[self.neighbor_indices]
        
        # Extract point features using precomputed indices
        point_features = example[self.point_indices]
        
        # Combine neighbor and point features
        features = torch.cat([neighbor_features, point_features])
        
        # Normalize per-example before applying transforms
        features = self._normalize_patches(features)
        
        # Extract target (p_u)
        if self.has_r1_min_in_data:
            target = example[-1]  # p_u is last when r1_min_val exists
        else:
            target = example[-1]  # p_u is last
        
        # Apply transform if specified
        if self.transform is not None:
            features = self.transform(features)
        
        return features, target
    
    def _normalize_examples(self) -> torch.Tensor:
        """
        Normalize all examples in the dataset (per-example normalization).
        
        This modifies self.examples in-place.
        """
        self._normalize_patches(self.examples)
        
        print(f"Normalized all examples in the dataset.")
        return self.examples

    
    def _normalize_patches(self, features: torch.Tensor) -> torch.Tensor:
        """
        Normalize a patch's features (or batch of features).
        Works on EXTRACTED features (only requested attributes).
        
        Args:
            features: Concatenated neighbor and point features
                     Shape: (feature_dim,) for single example
                     Shape: (batch_size, feature_dim) for batch
            
        Returns:
            Normalized features with same shape as input
        """
        import math
        
        # Handle both single example and batch
        is_batch = features.dim() > 1
        if not is_batch:
            features = features.unsqueeze(0)  # Add batch dimension
        
        batch_size = features.shape[0]
        
        # Normalize opacity (min-max to [0, 1]) per example
        if "opacity" in self.attr_positions_in_features:
            #normalize opacity (min-max to [0, 1]) per example
            pos_info = self.attr_positions_in_features["opacity"]
            neighbor_pos = pos_info['neighbor_positions']
            point_pos = pos_info['point_positions']
            
            # Get all opacity values (neighbors + point) for this example
            all_opacity = torch.cat([
                features[..., neighbor_pos],
                features[..., point_pos], 
            ], dim=-1)
            
            opacity_min = all_opacity.min(dim=-1, keepdim=True)[0]  # (batch_size, 1)
            opacity_max = all_opacity.max(dim=-1, keepdim=True)[0]  # (batch_size, 1)
     
            opacity_range = opacity_max - opacity_min
            opacity_range = torch.where(opacity_range > 0, opacity_range, torch.ones_like(opacity_range))
            features[:, neighbor_pos] = (features[:, neighbor_pos] - opacity_min) / opacity_range
            features[:, point_pos] = (features[:, point_pos] - opacity_min) / opacity_range

        
        # Normalize SH features (transformation)
        if "sh" in self.attr_positions_in_features:
            pos_info = self.attr_positions_in_features["sh"]
            neighbor_pos = pos_info['neighbor_positions']
            point_pos = pos_info['point_positions']
            
            # Apply transformation (can be done for entire batch)
            features[:, neighbor_pos] = features[:, neighbor_pos] * 0.28209479177387814
            features[:, neighbor_pos] = torch.clamp(features[:, neighbor_pos], -0.5, 0.5)
            features[:, neighbor_pos] = 2 * features[:, neighbor_pos] / math.sqrt(3)
            
            features[:, point_pos] = features[:, point_pos] * 0.28209479177387814
            features[:, point_pos] = torch.clamp(features[:, point_pos], -0.5, 0.5)
            features[:, point_pos] = 2 * features[:, point_pos] / math.sqrt(3)
        
        # Normalize scale (point cloud normalization) per example
        if "scale" in self.attr_positions_in_features:
            pos_info = self.attr_positions_in_features["scale"]
            neighbor_pos = pos_info['neighbor_positions']
            point_pos = pos_info['point_positions']
            
            num_neighbors = len(neighbor_pos) // 3
            # Reshape to (batch_size, num_neighbors + 1, 3)
            neighbor_scales = features[..., neighbor_pos].view(-1, num_neighbors, 3)
            point_scale = features[..., point_pos].view(-1, 1, 3)
            all_scales = torch.cat([neighbor_scales, point_scale], dim=1)
                
            # Compute centroid
            centroid = all_scales.mean(dim=1, keepdim=True)  # (batch_size, 1, 3)
            
            # Center the data
            scales_centered = all_scales - centroid  # (batch_size, num_neighbors + 1, 3)
            
            # Compute max distance from origin
            distances = torch.sqrt(torch.sum(scales_centered**2, dim=2))  # (batch_size, num_neighbors + 1)
            m = distances.max(dim=1, keepdim=True)[0].unsqueeze(-1)  # (batch_size, 1, 1)
            
            # Normalize
            scales_normalized = torch.where(
                m > 0,
                scales_centered / m,
                scales_centered
            )
            
            # Update features
            features[:, neighbor_pos] = scales_normalized[:, :num_neighbors].reshape(batch_size, -1)
            features[:, point_pos] = scales_normalized[:, -1, :]
        
        # Remove batch dimension if input was single example
        if not is_batch:
            features = features.squeeze(0)
        
        return features
    
    def get_ring(self) -> int:
        """
        Get the ring number for this dataset.
        
        Returns:
            Ring number
        """
        return self.ring
    
    def get_metadata(self) -> Optional[Dict]:
        """Return the metadata dictionary if available."""
        return self.metadata
    
    def get_config(self) -> Optional[Dict]:
        """Return the config dictionary if available."""
        return self.config
    
    def get_ring_info(self) -> Dict:
        """Return information about loaded rings."""
        return self.ring_info
    
    def print_info(self):
        """Print dataset information."""
        print("="*80)
        print("Gaussian Patch Dataset Information")
        print("="*80)
        print(f"Data directory: {self.data_dir}")
        print(f"Ring: {self.ring}")
        print(f"Total examples: {len(self)}")
        print(f"Feature dimension: {self.feature_dim}")
        print(f"Use r1_min: {self.use_r1_min}")
